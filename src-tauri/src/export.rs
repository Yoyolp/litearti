//! Writing exported files to a directory the person picked.
//!
//! The frontend does the conversion; this module only has to put bytes on disk
//! safely. Three rules drive it, and each exists because of a specific way
//! naive file writing loses data:
//!
//! 1. **Never overwrite.** Two books can share a title, and an export that
//!    silently replaces a file already in the folder is data loss. Collisions
//!    get a ` (2)` suffix instead.
//! 2. **Sanitize the name.** Titles come from filenames and can contain `:`,
//!    `?`, or a Windows device name like `CON`. The frontend sanitizes too, but
//!    this side is what actually touches the filesystem, so it must not trust
//!    anything that crossed IPC.
//! 3. **Write atomically.** A `.tmp` file plus a rename means an interrupted
//!    export leaves either the old file or the new one, never a truncated one.

use crate::error::{AppError, AppResult};
use serde::{Deserialize, Serialize};
use std::fs;
use std::path::{Path, PathBuf};

/// One file to write. Bytes are sent over IPC rather than a source path, so
/// nothing here can be tricked into reading from an arbitrary location.
#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ExportItem {
    pub file_name: String,
    pub bytes: Vec<u8>,
}

/// A file the backend refused to write, reported rather than thrown so one
/// failure does not abort the batch.
#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ExportFailure {
    pub file_name: String,
    pub reason: String,
}

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ExportOutcome {
    pub written: usize,
    /// Final names on disk, which may differ from the requested ones after
    /// collision handling — the UI reports these so the message matches reality.
    pub written_names: Vec<String>,
    pub failed: Vec<ExportFailure>,
}

/// Characters Windows forbids in a filename, plus the path separators.
fn sanitize_stem(title: &str) -> String {
    const ILLEGAL: &[char] = &['\\', '/', ':', '*', '?', '"', '<', '>', '|'];

    let mut stem: String = title
        .chars()
        .map(|c| {
            // Control characters are illegal in names on every platform.
            if ILLEGAL.contains(&c) || (c as u32) < 0x20 {
                '_'
            } else {
                c
            }
        })
        .collect();

    // Collapse whitespace runs, then strip leading/trailing dots and spaces.
    stem = stem.split_whitespace().collect::<Vec<_>>().join(" ");
    stem = stem.trim_matches(|c: char| c == '.' || c.is_whitespace()).to_string();

    if stem.is_empty() {
        stem = "未命名".to_string();
    }

    // Windows device names are reserved regardless of extension.
    const RESERVED: &[&str] = &[
        "con", "prn", "aux", "nul", "com1", "com2", "com3", "com4", "com5", "com6", "com7", "com8",
        "com9", "lpt1", "lpt2", "lpt3", "lpt4", "lpt5", "lpt6", "lpt7", "lpt8", "lpt9",
    ];
    if RESERVED.contains(&stem.to_lowercase().as_str()) {
        stem = format!("_{stem}");
    }

    // Keep well under the filesystem limit; CJK is three bytes per character.
    if stem.chars().count() > 80 {
        stem = stem.chars().take(80).collect::<String>().trim().to_string();
    }

    if stem.is_empty() {
        "未命名".to_string()
    } else {
        stem
    }
}

/// Split `name.ext` into stem and extension, treating a leading dot as part of
/// the stem (so `.gitignore` keeps its dot).
fn split_name(file_name: &str) -> (String, String) {
    match file_name.rfind('.') {
        Some(index) if index > 0 => (
            file_name[..index].to_string(),
            file_name[index..].to_string(),
        ),
        _ => (file_name.to_string(), String::new()),
    }
}

/// Apply the sanitizer to a full requested filename, keeping its extension.
fn sanitize_file_name(file_name: &str) -> String {
    let (stem, extension) = split_name(file_name);
    // The extension is generated by our own registry, but a defensive trim
    // costs nothing and prevents a stray path separator from escaping.
    let extension: String = extension
        .chars()
        .filter(|c| !['\\', '/', ':', '*', '?', '"', '<', '>', '|'].contains(c))
        .collect();
    format!("{}{}", sanitize_stem(&stem), extension)
}

/// Find a free name, appending ` (2)`, ` (3)`, … as needed.
///
/// `taken` holds names already claimed during this same export, which the
/// filesystem cannot tell us about yet.
fn unique_name(dir: &Path, file_name: &str, taken: &mut std::collections::HashSet<String>) -> AppResult<String> {
    let (stem, extension) = split_name(file_name);

    for attempt in 1..=999 {
        let candidate = if attempt == 1 {
            file_name.to_string()
        } else {
            format!("{stem} ({attempt}){extension}")
        };

        let key = candidate.to_lowercase();
        if taken.contains(&key) {
            continue;
        }
        if !dir.join(&candidate).exists() {
            taken.insert(key);
            return Ok(candidate);
        }
    }

    Err(AppError::Invalid(format!(
        "同名文件过多，无法为「{file_name}」找到可用的名字"
    )))
}

/// Write every item into `dir`.
///
/// The directory must already exist: it comes from a native folder picker, and
/// creating it here would mask a typo in a path the person did not mean to use.
pub fn write_many(dir: &Path, items: &[ExportItem]) -> AppResult<ExportOutcome> {
    if !dir.is_dir() {
        return Err(AppError::Invalid(format!(
            "导出目录不存在：{}",
            dir.display()
        )));
    }

    let mut written = 0usize;
    let mut written_names = Vec::new();
    let mut failed = Vec::new();
    let mut taken = std::collections::HashSet::new();

    for item in items {
        let safe = sanitize_file_name(&item.file_name);

        match write_one(dir, &safe, &item.bytes, &mut taken) {
            Ok(final_name) => {
                written += 1;
                written_names.push(final_name);
            }
            Err(error) => failed.push(ExportFailure {
                file_name: item.file_name.clone(),
                reason: error.to_string(),
            }),
        }
    }

    Ok(ExportOutcome {
        written,
        written_names,
        failed,
    })
}

/// Write one file atomically, returning the name it landed on.
fn write_one(
    dir: &Path,
    file_name: &str,
    bytes: &[u8],
    taken: &mut std::collections::HashSet<String>,
) -> AppResult<String> {
    let final_name = unique_name(dir, file_name, taken)?;
    let target: PathBuf = dir.join(&final_name);

    // A sibling temp name keeps the rename on the same filesystem, which is
    // what makes it atomic.
    let temp = dir.join(format!(".{final_name}.tmp"));
    fs::write(&temp, bytes)?;

    if let Err(error) = fs::rename(&temp, &target) {
        // Leaving a temp file behind after a failed rename would slowly litter
        // the export folder.
        let _ = fs::remove_file(&temp);
        return Err(error.into());
    }

    Ok(final_name)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sanitizes_illegal_characters() {
        assert_eq!(sanitize_stem("a:b*c?d"), "a_b_c_d");
        assert_eq!(sanitize_stem("path/to\\file"), "path_to_file");
    }

    #[test]
    fn strips_trailing_dots_and_spaces() {
        assert_eq!(sanitize_stem("  name...  "), "name");
    }

    #[test]
    fn keeps_chinese_intact() {
        assert_eq!(sanitize_stem("安静地读：一个阅读器的设计笔记"), "安静地读：一个阅读器的设计笔记");
    }

    #[test]
    fn empty_title_falls_back() {
        assert_eq!(sanitize_stem("   "), "未命名");
        assert_eq!(sanitize_stem("..."), "未命名");
    }

    #[test]
    fn reserved_names_are_prefixed() {
        assert_eq!(sanitize_stem("CON"), "_CON");
        assert_eq!(sanitize_stem("nul"), "_nul");
    }

    #[test]
    fn splits_extension() {
        assert_eq!(split_name("a.txt"), ("a".to_string(), ".txt".to_string()));
        assert_eq!(split_name("a"), ("a".to_string(), String::new()));
        assert_eq!(split_name(".gitignore"), (".gitignore".to_string(), String::new()));
        assert_eq!(split_name("a.b.c"), ("a.b".to_string(), ".c".to_string()));
    }

    #[test]
    fn sanitizes_full_name_but_keeps_extension() {
        assert_eq!(sanitize_file_name("a:b.txt"), "a_b.txt");
        assert_eq!(sanitize_file_name("no-ext"), "no-ext");
    }

    #[test]
    fn unique_name_increments_on_collision() {
        let dir = std::env::temp_dir().join(format!("litearti-export-test-{}", uuid::Uuid::new_v4()));
        fs::create_dir_all(&dir).unwrap();

        let mut taken = std::collections::HashSet::new();
        let first = unique_name(&dir, "book.txt", &mut taken).unwrap();
        assert_eq!(first, "book.txt");

        // Simulate the first file existing on disk.
        fs::write(dir.join(&first), b"x").unwrap();

        let mut taken2 = std::collections::HashSet::new();
        let second = unique_name(&dir, "book.txt", &mut taken2).unwrap();
        assert_eq!(second, "book (2).txt");

        fs::write(dir.join(&second), b"x").unwrap();
        let mut taken3 = std::collections::HashSet::new();
        let third = unique_name(&dir, "book.txt", &mut taken3).unwrap();
        assert_eq!(third, "book (3).txt");

        fs::remove_dir_all(&dir).ok();
    }

    #[test]
    fn unique_name_avoids_names_claimed_in_same_batch() {
        let dir = std::env::temp_dir().join(format!("litearti-export-batch-{}", uuid::Uuid::new_v4()));
        fs::create_dir_all(&dir).unwrap();

        let mut taken = std::collections::HashSet::new();
        // Neither file exists yet, but the first one claimed the name.
        let first = unique_name(&dir, "same.txt", &mut taken).unwrap();
        let second = unique_name(&dir, "same.txt", &mut taken).unwrap();
        assert_eq!(first, "same.txt");
        assert_eq!(second, "same (2).txt");

        fs::remove_dir_all(&dir).ok();
    }

    #[test]
    fn write_many_writes_and_reports() {
        let dir = std::env::temp_dir().join(format!("litearti-export-write-{}", uuid::Uuid::new_v4()));
        fs::create_dir_all(&dir).unwrap();

        let items = vec![
            ExportItem { file_name: "one.txt".into(), bytes: b"hello".to_vec() },
            ExportItem { file_name: "one.txt".into(), bytes: b"world".to_vec() },
        ];
        let outcome = write_many(&dir, &items).unwrap();

        assert_eq!(outcome.written, 2);
        assert_eq!(outcome.written_names, vec!["one.txt", "one (2).txt"]);
        assert_eq!(fs::read(dir.join("one.txt")).unwrap(), b"hello");
        assert_eq!(fs::read(dir.join("one (2).txt")).unwrap(), b"world");

        fs::remove_dir_all(&dir).ok();
    }

    #[test]
    fn missing_directory_is_rejected() {
        let dir = std::env::temp_dir().join("litearti-export-does-not-exist-xyz");
        let items = vec![ExportItem { file_name: "a.txt".into(), bytes: b"x".to_vec() }];
        assert!(write_many(&dir, &items).is_err());
    }
}
